    /* ---------- Orders and immutable purchase snapshots ---------- */
    IF OBJECT_ID(N'dbo.Orders', N'U') IS NULL
    BEGIN
        CREATE TABLE dbo.Orders
        (
            OrderId BIGINT IDENTITY(1,1) NOT NULL
                CONSTRAINT PK_Orders PRIMARY KEY,
            OrderNumber NVARCHAR(32) NOT NULL,
            UserId INT NULL,
            CustomerName NVARCHAR(160) NOT NULL,
            CustomerEmail NVARCHAR(254) NOT NULL,
            CustomerPhone NVARCHAR(30) NOT NULL,
            ShippingAddress NVARCHAR(500) NOT NULL,
            ShippingWard NVARCHAR(120) NULL,
            ShippingDistrict NVARCHAR(120) NULL,
            ShippingCity NVARCHAR(120) NOT NULL,
            Subtotal DECIMAL(18,2) NOT NULL,
            ShippingFee DECIMAL(18,2) NOT NULL
                CONSTRAINT DF_Orders_ShippingFee DEFAULT (0),
            DiscountAmount DECIMAL(18,2) NOT NULL
                CONSTRAINT DF_Orders_DiscountAmount DEFAULT (0),
            TotalAmount DECIMAL(18,2) NOT NULL,
            OrderStatus NVARCHAR(24) NOT NULL
                CONSTRAINT DF_Orders_OrderStatus DEFAULT (N'pending'),
            PaymentMethod NVARCHAR(24) NOT NULL
                CONSTRAINT DF_Orders_PaymentMethod DEFAULT (N'cod'),
            PaymentStatus NVARCHAR(24) NOT NULL
                CONSTRAINT DF_Orders_PaymentStatus DEFAULT (N'unpaid'),
            CustomerNote NVARCHAR(1000) NULL,
            CreatedAt DATETIME2(0) NOT NULL
                CONSTRAINT DF_Orders_CreatedAt DEFAULT (SYSUTCDATETIME()),
            UpdatedAt DATETIME2(0) NOT NULL
                CONSTRAINT DF_Orders_UpdatedAt DEFAULT (SYSUTCDATETIME()),
            CONSTRAINT UQ_Orders_OrderNumber UNIQUE (OrderNumber),
            CONSTRAINT FK_Orders_Users FOREIGN KEY (UserId)
                REFERENCES dbo.Users (UserId) ON DELETE SET NULL,
            CONSTRAINT CK_Orders_Amounts CHECK
                (Subtotal >= 0 AND ShippingFee >= 0 AND DiscountAmount >= 0 AND TotalAmount >= 0),
            CONSTRAINT CK_Orders_Status CHECK
                (OrderStatus IN (N'pending', N'confirmed', N'shipping', N'completed', N'cancelled')),
            CONSTRAINT CK_Orders_PaymentMethod CHECK
                (PaymentMethod IN (N'cod', N'bank_transfer', N'online')),
            CONSTRAINT CK_Orders_PaymentStatus CHECK
                (PaymentStatus IN (N'unpaid', N'pending', N'paid', N'refunded', N'failed'))
        );
    END;
    GO

    IF OBJECT_ID(N'dbo.OrderItems', N'U') IS NULL
    BEGIN
        CREATE TABLE dbo.OrderItems
        (
            OrderItemId BIGINT IDENTITY(1,1) NOT NULL
                CONSTRAINT PK_OrderItems PRIMARY KEY,
            OrderId BIGINT NOT NULL,
            ProductId INT NULL,
            ProductName NVARCHAR(180) NOT NULL,
            ProductSlug NVARCHAR(100) NOT NULL,
            UnitPrice DECIMAL(18,2) NOT NULL,
            Quantity INT NOT NULL,
            LineTotal AS (UnitPrice * Quantity) PERSISTED,
            CONSTRAINT FK_OrderItems_Orders FOREIGN KEY (OrderId)
                REFERENCES dbo.Orders (OrderId) ON DELETE CASCADE,
            CONSTRAINT FK_OrderItems_Products FOREIGN KEY (ProductId)
                REFERENCES dbo.Products (ProductId) ON DELETE SET NULL,
            CONSTRAINT CK_OrderItems_UnitPrice CHECK (UnitPrice >= 0),
            CONSTRAINT CK_OrderItems_Quantity CHECK (Quantity > 0)
        );
    END;
    GO

