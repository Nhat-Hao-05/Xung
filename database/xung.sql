    /* ---------- Product catalog ---------- */
    IF OBJECT_ID(N'dbo.Categories', N'U') IS NULL
    BEGIN
        CREATE TABLE dbo.Categories
        (
            CategoryId INT IDENTITY(1,1) NOT NULL
                CONSTRAINT PK_Categories PRIMARY KEY,
            Slug NVARCHAR(80) NOT NULL,
            Name NVARCHAR(120) NOT NULL,
            Description NVARCHAR(500) NULL,
            IsActive BIT NOT NULL
                CONSTRAINT DF_Categories_IsActive DEFAULT (1),
            CreatedAt DATETIME2(0) NOT NULL
                CONSTRAINT DF_Categories_CreatedAt DEFAULT (SYSUTCDATETIME()),
            CONSTRAINT UQ_Categories_Slug UNIQUE (Slug)
        );
    END;
    GO

    IF OBJECT_ID(N'dbo.Products', N'U') IS NULL
    BEGIN
        CREATE TABLE dbo.Products
        (
            ProductId INT IDENTITY(1,1) NOT NULL
                CONSTRAINT PK_Products PRIMARY KEY,
            Slug NVARCHAR(100) NOT NULL,
            CategoryId INT NOT NULL,
            Name NVARCHAR(180) NOT NULL,
            ShortDescription NVARCHAR(500) NOT NULL,
            Specifications NVARCHAR(1000) NOT NULL,
            Detail NVARCHAR(1000) NOT NULL,
            ImageUrl NVARCHAR(500) NOT NULL,
            Badge NVARCHAR(80) NULL,
            Price DECIMAL(18,2) NOT NULL,
            CompareAtPrice DECIMAL(18,2) NULL,
            Rating DECIMAL(2,1) NOT NULL
                CONSTRAINT DF_Products_Rating DEFAULT (0),
            ReviewCount INT NOT NULL
                CONSTRAINT DF_Products_ReviewCount DEFAULT (0),
            StockQuantity INT NOT NULL
                CONSTRAINT DF_Products_StockQuantity DEFAULT (0),
            IsFeatured BIT NOT NULL
                CONSTRAINT DF_Products_IsFeatured DEFAULT (0),
            IsActive BIT NOT NULL
                CONSTRAINT DF_Products_IsActive DEFAULT (1),
            CreatedAt DATETIME2(0) NOT NULL
                CONSTRAINT DF_Products_CreatedAt DEFAULT (SYSUTCDATETIME()),
            UpdatedAt DATETIME2(0) NOT NULL
                CONSTRAINT DF_Products_UpdatedAt DEFAULT (SYSUTCDATETIME()),
            CONSTRAINT UQ_Products_Slug UNIQUE (Slug),
            CONSTRAINT FK_Products_Categories FOREIGN KEY (CategoryId)
                REFERENCES dbo.Categories (CategoryId),
            CONSTRAINT CK_Products_Price CHECK (Price >= 0),
            CONSTRAINT CK_Products_CompareAtPrice CHECK
                (CompareAtPrice IS NULL OR CompareAtPrice >= Price),
            CONSTRAINT CK_Products_Rating CHECK (Rating >= 0 AND Rating <= 5),
            CONSTRAINT CK_Products_ReviewCount CHECK (ReviewCount >= 0),
            CONSTRAINT CK_Products_StockQuantity CHECK (StockQuantity >= 0)
        );
    END;
    GO

    /* ---------- Accounts ---------- */
    IF OBJECT_ID(N'dbo.Users', N'U') IS NULL
    BEGIN
        CREATE TABLE dbo.Users
        (
            UserId INT IDENTITY(1,1) NOT NULL
                CONSTRAINT PK_Users PRIMARY KEY,
            FullName NVARCHAR(160) NOT NULL,
            Email NVARCHAR(254) NOT NULL,
            PasswordHash NVARCHAR(255) NOT NULL,
            Phone NVARCHAR(10) NULL,
            Address NVARCHAR(300) NOT NULL,
            Gender NVARCHAR(20) NOT NULL,
            IdentityNumberHash CHAR(64) NULL,
            IdentityNumberEncrypted NVARCHAR(128) NULL,
            Role NVARCHAR(20) NOT NULL
                CONSTRAINT DF_Users_Role DEFAULT (N'customer'),
            IsEmailVerified BIT NOT NULL
                CONSTRAINT DF_Users_IsEmailVerified DEFAULT (0),
            IsActive BIT NOT NULL
                CONSTRAINT DF_Users_IsActive DEFAULT (1),
            CreatedAt DATETIME2(0) NOT NULL
                CONSTRAINT DF_Users_CreatedAt DEFAULT (SYSUTCDATETIME()),
            UpdatedAt DATETIME2(0) NOT NULL
                CONSTRAINT DF_Users_UpdatedAt DEFAULT (SYSUTCDATETIME()),
            CONSTRAINT UQ_Users_Email UNIQUE (Email),
            CONSTRAINT CK_Users_Gender CHECK
                (Gender IN (N'male', N'female', N'other', N'unspecified'))
        );
    END;
    GO

